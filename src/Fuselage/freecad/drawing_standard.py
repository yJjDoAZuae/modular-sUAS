TEMPLATE_FRAME_ID = 'rect3675'
TEMPLATE_FRAME_MM = (20.107, 14.473, 239.52, 187.2)
TEMPLATE_TITLE_BLOCK_ID = 'rect2985'
TEMPLATE_TITLE_BLOCK_MM = (129.627, 155.673, 130.0, 46.0)

# --------------------------------------------------------------------------------------
# The value table's layout, decided in OQ-DES-D5 on 2026-08-22
# --------------------------------------------------------------------------------------

# **The requirement all four of these serve**: the drawn view takes at least this share of the
# frame, and the title block and the value table share what is left. It is stated as a
# fraction rather than as millimeters because it is the thing being held constant while the
# sheet size and the table's contents are not.
VIEW_SHARE = 0.75

#: Table text heights to try, largest first, when packing a family sheet's blocks into the
#: band beside the title block.
#:
#: **The lettering is what gives, and that is a decision rather than a shortcut.** The three
#: blocks a family sheet carries besides the view -- the value table, the dimension key and
#: the sheet-coverage block -- come to about 11,600 mm2 at ISO 3098's smallest 2.5 mm, and
#: the frame is 44,834 with 5,980 of it under the title block. For the view to have the 75 %
#: `VIEW_SHARE` asks for, the three of them have to fit 5,229 -- which is 45 % of the area
#: and so 67 % of the linear size, about 1.7 mm of text. Packing waste takes it to 1.4.
#:
#: A drawing whose geometry cannot be read is not saved by a legible table beside it. So the
#: search runs down this series until the blocks fit the band, and the sheet keeps its view.
TABLE_TEXT_HEIGHTS_MM = (2.5, 2.2, 2.0, 1.8, 1.6, 1.4, 1.2, 1.0)

# A value table's row pitch, as a multiple of *its* text height. **1.4, which is ISO 3098's
# minimum line spacing for type B lettering** -- the same standard the text heights come from,
# so it is a number the drawing convention fixes rather than one this module picks.
#
# **Two wrong values preceded it and both are worth recording.** It was 2.0, the pitch
# `dimension_placement.LANE_PITCH_HEIGHTS` puts between dimension lines, taken so the sheet
# would have one vertical rhythm rather than two -- an argument about how the sheet looks,
# made before anyone had measured what the rhythm cost. OQ-DES-D5 measured it and took it to
# **1.3**, which fit the band and is **below the standard's minimum**: the same 1.4 was cited
# three files away as ISO 3098's floor for note line spacing, and the table was set tighter
# than it to make an arithmetic problem go away. That is exactly what section 5.4 warns of --
# *the knobs get tuned per drawing until the rules no longer mean anything*.
#
# The arithmetic problem was real and had a different answer, below.
TABLE_ROW_PITCH_HEIGHTS = 1.4

# **And 1.4 is not enough on its own, because a table row is ruled and a line of prose is
# not.** ISO 3098's 1.4 is the minimum distance between two *baselines*, which keeps one line
# of text off the next. A table row additionally has a line drawn along its edge, and what
# must clear that line is the glyph box -- `EM_PER_TEXT_HEIGHT` cap heights tall, 1.328, so at
# a 1.4 pitch the box leaves 0.07 of a cap height, 0.18 mm, to the rule above and below.
# Rendered, that reads as a rule struck through the text: measured 2026-09-07, the first data
# row of every value table and the heading above it were both touching the rule between them.
#
# So a row clears its rules by this much on each side, and the pitch is whichever requirement
# is the stricter.
#
# **A quarter of a cap height, and the number is only meaningful because the cells are placed
# correctly.** Raising it to 0.4 was tried while the first data row of every block was touching
# the rule above it, and it did not help, because the row was not short of space: it was drawn
# half a cap height high, a `DrawViewAnnotation` being positioned by its baseline rather than
# by the middle of its text (see `drawing.add_table`). Widening a row to fix text that is
# outside its row is the kind of tuning section 5.4 warns about -- it would have left every
# table a third taller for nothing, and on these sheets that came straight out of the view,
# taking two bulkheads from 1:1 to 1:2. With the placement right, this leaves 1.08 mm of white
# between the ink and a rule drawn 0.76 mm thick.
TABLE_ROW_CLEARANCE_HEIGHTS = 0.25

# The same requirement on the other axis, and it had the same hole. `column_width_mm` returned
# exactly the width of the widest string a column prints, so the widest value in every column
# ran from one rule to the other with nothing between: measured 2026-09-07, all thirteen
# columns of the bulkhead table came out width == need, to the millimetre, and `0.75` in the
# `U` column drew across its own left-hand rule. A cell needs white space beside it for the
# same reason a row needs white space above it -- the rule is 0.76 mm of ink, and a gap
# narrower than that does not read as a gap.
TABLE_COLUMN_PADDING_HEIGHTS = 0.35

# The clear gap between two columns of a value table, in millimeters -- **not a multiple of
# the text height, and that is the correction**. This was one text height, taken from section
# 5.2's H2 on the reasoning that H2 requires one text height between two text blocks and a
# table column is a column of digits beside another column of digits.
#
# H2 governs annotations **floating on a view with nothing between them**, where the gap is
# the only thing separating two numbers. A table has a rule between its columns, which is what
# a rule is for. Applied where it does not apply, H2 was the single largest thing making the
# table too wide: it cost 25 mm on the widest family, more than every other compaction
# together.
#
# **That justification is a debt on the table renderer, not a free saving.** 1.0 mm between two
# columns of digits is 0.4 of a text height and it is only enough because a rule is drawn
# between them. A table drawn without rules at this gutter is the failure H2 describes, and the
# renderer does not exist yet -- so this is written down here rather than left as an assumption
# somebody would have to reconstruct from a number.
TABLE_COLUMN_GUTTER_MM = 1.0

# **The value table sets one size smaller than the view.** 2.5 mm is the next size down in ISO
# 3098's preferred series, not a fraction chosen to fit, and a table setting smaller than the
# annotations around it is what every title block and parts list on every drawing does -- a
# column of digits under a heading is read differently from a number floating beside a feature.
#
# It was the view's 3.5 mm until 2026-08-27, and that was never a decision: nothing chose it,
# the table simply inherited `TEXT_HEIGHT_MM` because there was one constant. The cost of the
# inheritance was the whole of a reported blocker -- at 3.5 mm the panelled corner's table is
# 138.9 mm into a 108.5 mm band, and at 2.5 mm it is **104.0 mm, which fits** -- so a value
# nobody had picked was about to buy a change to the shape of the drawing set.
#
# **This is also what pays for the row pitch above.** At 3.5 mm text and the standard's 1.4 h
# spacing the table is 49.0 mm deep against a 46.8 mm band; at 2.5 mm it is 35.0.
TABLE_TEXT_HEIGHT_MM = 2.5

# Where the sheet puts the table and the title block. **The view's share is a packing result
# and not an area subtraction**, because a view is a projection with a bounding box, so what
# it gets is the largest *rectangle* left once the other two are placed. Only these two leave
# a rectangle at all:
#
#   band    title block and table side by side across the bottom, the view full width above.
#           The band is as deep as the deeper of the two.
#   column  table stacked above the title block on one side, the view full height beside. The
#           column is as wide as the **wider** of the two, so a table narrower than the title
#           block gains nothing by being narrower.
#
# Measured 2026-08-22: the band gives the view 75.7 % and the column 38.4 %, on the same
# table. Which one is available is decided by whether the table fits beside the title block.
PLACEMENT_BAND = 'band'
PLACEMENT_COLUMN = 'column'


