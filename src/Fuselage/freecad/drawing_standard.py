# does not carry is not reproducible from the project, and two machines with different FreeCAD
# versions would emit different sheets from the same source. It is now beside this module and
# generated by `tools/make_sheet_template.py`, whose docstring carries the derivation.
TEMPLATE_RELPATH = ('templates', 'fuselage_ansi_a_landscape.svg')
TEMPLATE_WIDTH_MM = 279.4
TEMPLATE_HEIGHT_MM = 215.9

# The one thing the stock ASME template could not do, and the reason OQ-DES-D5's decision is
# worth more than the millimeters it recovered: **the sheet states its units**. A cell in a
# value table is a bare number and so is an annotation, so without this the drawing asserts
# nothing about what its numbers mean. It is fixed text rather than an editable field, because
# an editable field can be filled in blank and this must not be able to go missing --
# `verify_template` fails the build if the string is absent.
TEMPLATE_UNITS_TEXT = 'DIMENSIONS IN MILLIMETERS'

# The fields TechDraw fills in from the document. Named here so `verify_template` can refuse a
