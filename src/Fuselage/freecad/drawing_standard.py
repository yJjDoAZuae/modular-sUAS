# The font
# --------------------------------------------------------------------------------------

# osifont is the ISO 3098 drawing face TechDraw ships in its own resources. It is pinned by
# name here rather than left to the empty preference group, and `verify_font` asserts that
# what is installed is what was measured.
#
# It is NOT vendored into this repository. Vendoring raises a licensing question -- osifont
# is LGPL-3 with a font exception -- which belongs to IP-FC-6's survey and not to a drawing
# module. Referencing the installed copy and *checking its metrics* closes the same hole
# without taking that decision: a substituted or updated font fails the build loudly instead
# of quietly changing every annotation's width.
FONT_NAME = 'osifont'
FONT_RELPATH = ('Mod', 'TechDraw', 'Resources', 'fonts', 'osifont-lgpl3fe.ttf')

# ISO 3098 preferred text heights are 2.5, 3.5, 5, 7, 10, 14 and 20 mm. 3.5 mm is the
# smallest of those that stays legible in a reduced print, which is how a shop drawing is
# usually read.
TEXT_HEIGHT_MM = 3.5

# Recorded from the pinned font on 2026-08-21 and re-asserted on every build by
# `verify_font`. Advances are in font design units; divide by UNITS_PER_EM and multiply by
# the text height to get millimeters.
UNITS_PER_EM = 2048

# **A text height on a drawing is a cap height, not an em size, and the difference is 33%.**
# ISO 3098 specifies `h` as the height of a capital, and TechDraw honours that: it scales the
# font so the ascender comes out at the `TextSize` it is given. Measured in the rendered page,
# 2026-09-07: text set to 2.5 mm draws at a 3.3 mm em and text set to 3.5 mm draws at 4.7 mm,
# both of which are `h * UNITS_PER_EM / TYPO_ASCENDER_UNITS` to the rounding the SVG writes.
#
# Every width here is an advance in design units, and an advance is a fraction *of the em*.
# Multiplying it by `h` therefore under-measures every string by that same 33% -- which is why
# the first rendered sheets had a value table whose columns were a third too narrow for their
# own contents, numbers lapping over the rules and headings running into their neighbours.
# `osifont` declares no `sCapHeight`, so the ascender is the metric to use, and it is pinned
# and re-checked like the advances beside it.
TYPO_ASCENDER_UNITS = 1542
EM_PER_TEXT_HEIGHT = UNITS_PER_EM / float(TYPO_ASCENDER_UNITS)


# ----------------------------------------------------------------------------------------
# Precision
# ----------------------------------------------------------------------------------------

# How many decimal places a length carries, and it is pinned here for the same reason the
# font is: it is not in the document either. TechDraw's `FormatSpec` defaults to two places
# from a compiled-in default -- `spike_techdraw.py` measured a 20 mm distance coming back as
# `20.00 mm` with nothing in the project asking for that -- so the number of digits a shop
# reads is currently inherited from a preference group that is empty on this machine.
#
# Two places is also the right number rather than merely the observed one. The tightest fit
# in the design is `longeron_tolerance` at 0.05 mm and `panel_tolerance` at 0.1 mm, so a
# hundredth resolves every clearance the parts are built to; a third place would print
# floating-point residue as though it were intent.
#
# **This is a drawing property with a measurement consequence.** `drawing_families.py` asks
# whether a dimension is a function of one size axis, and the honest form of that question is
# *at the precision the sheet prints*: a field that varies by 1e-13 with panel thickness is
# not a panel-dependent dimension on a sheet that writes two decimals. So the same constant
# decides the table's shape and the annotation's text, and it must not be two answers.
DECIMAL_PLACES = 2


def format_length(value_mm, decimals=DECIMAL_PLACES):
    """A length as it is written on the sheet.

    One function so the table cell, the annotation text and the separability test cannot
    disagree about what number a variant shows. `-0.00` is normalized to `0.00`: the sign of
    a value that rounds to zero is floating-point residue, and a drawing that prints it is
    stating a direction it does not mean.
    """
    text = '%.*f' % (decimals, value_mm)
    if float(text) == 0.0:
        text = '%.*f' % (decimals, 0.0)
    return text


# --------------------------------------------------------------------------------------
# Callouts
# --------------------------------------------------------------------------------------

# OQ-ARCH-7's family drawing puts a lettered callout on the view and the values in a table,
# so the text on a view is one capital and the set of strings a drawing can contain is known
# before any variant is built. That is what makes the extent a bound rather than a
# measurement, and it is the whole reason the placement problem is tractable.
#
# I, O and Q are omitted, which is drafting convention rather than preference: I reads as 1,
# and O and Q read as 0. A callout the reader mistakes for a digit is worse than one letter
# less of alphabet.
CALLOUT_ALPHABET = 'ABCDEFGHJKLMNPRSTUVWXYZ'

# The widest glyph in that alphabet, W, at 1559 units. Every callout is bounded by this one
# number, and -- because every callout is the same length -- the bound is *uniform*. A
# uniform over-estimate shifts a layout; it does not distort it. That distinction is why the
# family drawing makes a conservative bound nearly free, where on variable-length value text
# it would reject layouts that would have placed cleanly.
WIDEST_CALLOUT_UNITS = 1559
WIDEST_CALLOUT_CHAR = 'W'


# --------------------------------------------------------------------------------------
# The value table
# --------------------------------------------------------------------------------------

# The table is the one place on the sheet where variable-length value text survives, so it
# does not get the callout bound. It does not need the collision machinery either: sizing a
# column is a grid problem, each column as wide as its widest cell.
#
# **osifont's digits are not tabular**, which is worth stating because it is the natural
# assumption for a drawing face and it is false here: '1' is 700 units and '8' is 1056, a
# 50 % spread. So a column cannot be sized by counting characters. Bounding each digit
# position by the widest digit is correct and cheap.
WIDEST_DIGIT_UNITS = 1056
WIDEST_DIGIT_CHAR = '8'
DECIMAL_POINT_UNITS = 412
MINUS_UNITS = 952


def resource_dir():
    """FreeCAD's installed data directory. Imported lazily so this module reads anywhere.

    `units.py` makes the same choice for the same reason: a module that states the project's
    conventions should be readable by any interpreter, not only by one with FreeCAD in it.
    """
    import FreeCAD as App
    return App.getResourceDir()


def template_path(resource=None):
    """Absolute path to the pinned sheet template, which lives in this repository.

    `resource` is accepted so a caller can point at another tree, and is *not* FreeCAD's
    resource directory any more -- the template is the project's own since IP-FC-86. The font
    still comes from the installation, deliberately: vendoring it raises a licensing question
    that belongs to IP-FC-6, and `verify_font` closes the same hole by asserting its metrics.
    """
    return os.path.join(resource or os.path.dirname(os.path.abspath(__file__)),
                        *TEMPLATE_RELPATH)


def font_path(resource=None):
    """Absolute path to the pinned drawing font."""
    return os.path.join(resource or resource_dir(), *FONT_RELPATH)


def table_region_mm(width_mm=None):
    """Where a value table goes, as (x, y, width, height) in template coordinates.

    **The table sits beside the title block in a band across the bottom of the frame**, which
    is what OQ-DES-D5 decided: it is the only placement that leaves the drawn view a rectangle
    of the share the requirement asks for. Its depth is `table_band_depth_mm`.

    **Its width is not pinned, and an early version of this function pinning it to the title
    block's was wrong.** That looked derived because on ANSI A the title block is 146.7 of the
    frame's 239.5 mm and dividing the sheet there is tidy. It is a coincidence of one paper
    size: the ASME title block is *the same 146.7 mm* on ANSI B, where the frame is 391.8, so
    the same rule would give a B-size sheet no more table than an A-size one. A rule that
    ignores the sheet it is applied to is not a derivation.

    Its width is its content's. An early version pinned it to the title block's, which looked
    derived and was a coincidence of one paper size -- the ASME block is *the same* 146.7 mm on
    ANSI B, where the frame is 391.8, so the rule would have given a B-size sheet no more table
    than an A-size one. A rule that ignores the sheet it is applied to is not a derivation.

    Pass a width to place a real table; pass none for the widest one the band can hold beside
    the title block.
    """
    frame_x, frame_y, frame_w, frame_h = TEMPLATE_FRAME_MM
    _block_x, _block_y, block_w, _block_h = TEMPLATE_TITLE_BLOCK_MM
    available = frame_w - block_w - TABLE_COLUMN_GUTTER_MM
    width = available if width_mm is None else float(width_mm)
    depth = table_band_depth_mm()
    return (frame_x, frame_y + frame_h - depth, width, depth)


def view_region_mm(table_width_mm=None):
    """Where the view and its annotations go, as (x, y, width, height).

    The frame less the table's actual width and one column gutter, at the frame's full height
    because the title block does not reach across it. With no table beside it -- the table on a
    sheet of its own -- the view has the whole frame.

    This width is the number section 5.2's H1 is actually tested against. Measured 2026-08-22
    on the corner: its family sheet, four OQ-DES-D2 notes and six dimensions, needs **84.5 mm**
    and its single-variant sheet needs **100.0 mm**, at the frame's full height. Those are what
    a table's width has to leave behind.
    """
    frame_x, frame_y, frame_w, frame_h = TEMPLATE_FRAME_MM
    if table_width_mm is None:
        return (frame_x, frame_y, frame_w, frame_h)
    gutter = TABLE_COLUMN_GUTTER_MM
    return (frame_x, frame_y, frame_w - float(table_width_mm) - gutter, frame_h)


def frame_region_mm():
    """The whole frame, as (x, y, width, height).

    The width budget when the table is on a sheet of its own rather than beside the view.
    """
    frame_x, frame_y, frame_w, frame_h = TEMPLATE_FRAME_MM
    return (frame_x, frame_y, frame_w, frame_h)


# ----------------------------------------------------------------------------------------
# Line weights, and where they have to be applied
# ----------------------------------------------------------------------------------------

# **ISO 128 line group 0.5**, which is the group that goes with 3.5 mm lettering: a wide line
# of 0.5 mm and a narrow one of 0.25, in a 2:1 ratio. Outlines are wide; everything that is
# not the part -- hidden edges, dimension and extension lines, leaders, the value table's own
# rules -- is narrow.
#
# **These are not properties of the drawing document, and that is the trap.** Line weight,
# dimension text size and hole centre marks live on TechDraw's *view providers*, which are Gui
# objects. The sheets are built by `freecadcmd`, which has none, so an `.FCStd` from this
# project carries no appearance at all and whatever opens it supplies the lot from compiled-in
# defaults. Measured 2026-09-07, those defaults are: every view drawn at **0.7 mm** including
# the value table's rules, dimension text at **5.0 mm** against the 3.5 this standard sets,
# and `ArcCenterMarks` **off**, so not one hole on any sheet had a centre mark. None of that
# was chosen; all of it was inherited. `freecad/render_pages.py` applies this table before it
# builds the page scene, which is the only moment at which these objects exist.
WIDE_LINE_MM = 0.5
NARROW_LINE_MM = 0.25

# The arrowhead. ISO 129 draws it about ten narrow-line-widths long, and it must not out-weigh
# 3.5 mm text sitting beside it.
ARROW_SIZE_MM = 2.5

#: How a view whose edges are table rules is named. Those are `DrawViewPart`s like the drawn
#: view -- see `drawing.add_table` for why the rules are real geometry -- so they cannot be
#: told apart by type, only by name, and they must not be drawn at outline weight. Matched by
#: suffix because there is more than one of them: the value table's and the dimension key's.
RULE_VIEW_SUFFIX = 'RuleView'


def view_appearance(name=None):
    """View-provider settings for a `DrawViewPart`, as {property: value}.

    Pass the object's name so the value table's rule view gets narrow lines: its edges are a
    table, not an outline, and at outline weight the rules out-weigh the numbers between them.
    """
    if name and name.endswith(RULE_VIEW_SUFFIX):
        return {'LineWidth': NARROW_LINE_MM,
                'HiddenWidth': NARROW_LINE_MM,
                'IsoWidth': NARROW_LINE_MM,
                'ArcCenterMarks': False}
    return {'LineWidth': WIDE_LINE_MM,
            'HiddenWidth': NARROW_LINE_MM,
            'IsoWidth': NARROW_LINE_MM,
            # **Off, and the marks are drawn instead.** `ArcCenterMarks` is one switch for the
            # whole view: it marks every arc the projection produced, which on a bulkhead means
            # every fillet and every lead-in as well as the four bores and the four bolts. A
            # centre mark asserts an axis a feature is located from, and a fillet has no such
            # axis -- the marks on them are noise sitting exactly where the located features
            # are, which is the worst place for it. There is no per-arc control, so the switch
            # goes off and `sheet_annotations` names the axes that get one.
            'ArcCenterMarks': False,
            'CenterScale': 1.0}


# ---------------------------------------------------------------------------------------
# Construction geometry: centre marks, centre lines, and the outlines of adjacent parts
# ---------------------------------------------------------------------------------------
#
# **These are cosmetic edges, and a cosmetic edge carries its own format in the document.**
# That is the whole reason this is possible headlessly. Line weight on a *view* is a
# view-provider property and a document built by `freecadcmd` has none -- which is why
# `view_appearance` above exists and has to be applied by the renderer. A cosmetic edge's
# style, weight, colour and visibility live in the edge itself, in the saved file, so
# construction geometry drawn here looks the same wherever the page is opened.
#
# Verified 2026-09-07 against FreeCAD 1.1.3: `CosmeticEdge.Format` is a dict with the keys
# `style`, `weight`, `color`, `visible`, lowercase. Capitalised keys are rejected.

#: ISO 128 line types, as the `style` a `CosmeticEdge.Format` takes. Qt pen-style numbering,
#: which is what TechDraw stores.
LINE_CONTINUOUS = 1
LINE_DASHED = 2
LINE_DOTTED = 3
#: Long-dash dotted: ISO 128 type G, the centre line.
LINE_CENTER = 4
#: Long-dash double-dotted: ISO 128 type K, which is what an adjacent part is drawn in.
LINE_PHANTOM = 5

#: Ink for construction geometry. Black, like everything else the sheet prints -- a
#: construction line is distinguished by its *dash pattern*, which survives a photocopier and
#: a monochrome plot, and not by being grey, which does not.
CONSTRUCTION_COLOR = (0.0, 0.0, 0.0, 1.0)

#: How far a centre mark's arms reach past the feature they mark, as a fraction of its radius.
#: ISO 128 draws them a short way clear of the circle so the cross reads as belonging to it
#: rather than as part of it.
CENTER_MARK_OVERRUN = 1.35

#: How far a centre line runs past the geometry it is an axis of, in text heights. Enough to
#: read as a line rather than as a scratch, and short enough not to reach the frame.
CENTER_LINE_OVERRUN_HEIGHTS = 1.5


def center_mark_format():
    """The format a centre mark's arms are drawn in.

    **Continuous, not dash-dotted, and the reason is the scale the arms come out at.** A mark
    is a short cross -- a bore of R2.05 gives arms 2.77 mm long in the model, which at the
    bulkhead's 1:2 is 1.4 mm on the paper. A long-dash dotted pattern needs several
    millimetres to read as a pattern; below that it renders as a dot, a gap, or nothing at
    all, and a centre mark that sometimes disappears is worse than none. The long lines --
    the symmetry axes, where the pattern is what distinguishes an axis from an edge -- get
    the dashes.
    """
    return {'style': LINE_CONTINUOUS, 'weight': NARROW_LINE_MM,
            'color': CONSTRUCTION_COLOR, 'visible': True}


def center_line_format():
    """The format a symmetry axis is drawn in: long-dash dotted, ISO 128 type G."""
    return {'style': LINE_CENTER, 'weight': NARROW_LINE_MM,
            'color': CONSTRUCTION_COLOR, 'visible': True}


def detail_marker_format():
    """The format the circle round a detail's region is drawn in on the plan.

    Continuous and narrow, which is how ISO 128 draws a detail boundary -- it is a statement
    about the drawing rather than about the part, and a dashed one would read as a hidden
    feature at exactly the place a reader is being asked to look.
    """
    return {'style': LINE_CONTINUOUS, 'weight': NARROW_LINE_MM,
            'color': CONSTRUCTION_COLOR, 'visible': True}


def phantom_format():
    """The format an adjacent part's outline is drawn in.

    Narrow, because it is not this part's material -- a reference outline at outline weight
    reads as a feature of the part being made, which is the one thing it must not do.
    """
    return {'style': LINE_PHANTOM, 'weight': NARROW_LINE_MM,
            'color': CONSTRUCTION_COLOR, 'visible': True}


